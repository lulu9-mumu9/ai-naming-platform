-- 1. 历史记录表
create table if not exists name_history (
  id bigint generated by default as identity primary key,
  user_requirement text not null,          -- 用户的起名需求
  name_result text not null,               -- 模型生成的名字方案全文
  model_name text not null,                -- 本次使用的模型
  created_at timestamp with time zone default now()
);

-- 2. 常用排序索引（历史记录按时间倒序查询）
create index if not exists idx_name_history_created_at
  on name_history (created_at desc);


